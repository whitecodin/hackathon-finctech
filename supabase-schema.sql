-- Run in Supabase SQL Editor. Designed for a fresh Supabase project.
create table if not exists public.merchants (
 id bigint generated by default as identity primary key,
 user_id uuid not null unique references auth.users(id) on delete cascade,
 store_name text not null default 'My Shop',
 owner_name text not null default 'Merchant',
 category text not null default 'Grocery & Daily Essentials (Kirana)',
 location text not null default '',
 pin_code text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.transactions (
 id bigint generated by default as identity primary key,
 merchant_id bigint not null references public.merchants(id) on delete cascade,
 txn_ref text not null,
 date timestamptz not null default now(),
 counterparty text not null default '',
 amount numeric(12,2) not null check (amount>=0),
 type text not null check(type in ('inflow','outflow')),
 channel text not null default 'UPI',
 is_flagged boolean not null default false,
 status text not null default 'normal',
 merchant_note text
);
create table if not exists public.merchant_league_preferences(
 merchant_id bigint primary key references public.merchants(id) on delete cascade,
 opted_in boolean not null default false,
 display_alias text not null default 'Local Merchant',
 updated_at timestamptz not null default now()
);
create index if not exists transactions_merchant_date_idx on public.transactions(merchant_id,date desc);
alter table public.merchants enable row level security;
alter table public.transactions enable row level security;
alter table public.merchant_league_preferences enable row level security;
drop policy if exists "owner merchants" on public.merchants;
create policy "owner merchants" on public.merchants for all to authenticated using (user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
drop policy if exists "owner transactions" on public.transactions;
create policy "owner transactions" on public.transactions for all to authenticated using (exists(select 1 from public.merchants m where m.id=merchant_id and m.user_id=(select auth.uid()))) with check(exists(select 1 from public.merchants m where m.id=merchant_id and m.user_id=(select auth.uid())));
drop policy if exists "owner league prefs" on public.merchant_league_preferences;
create policy "owner league prefs" on public.merchant_league_preferences for all to authenticated using (exists(select 1 from public.merchants m where m.id=merchant_id and m.user_id=(select auth.uid()))) with check(exists(select 1 from public.merchants m where m.id=merchant_id and m.user_id=(select auth.uid())));
-- Server route uses user's bearer token; exposed tables never allow unrestricted public reads.
create or replace function public.create_my_shop()
returns public.merchants language sql security invoker as $$
 insert into public.merchants(user_id,store_name,owner_name)
 values(auth.uid(),'My Shop','Merchant')
 on conflict(user_id) do update set user_id=excluded.user_id
 returning *;
$$;
grant execute on function public.create_my_shop() to authenticated;
